#function to read jvm arguments
function readJvmProps($propFilePath)  {
    $jvmArgs = "";
    if ([System.IO.File]::Exists($propFilePath)) {
        foreach($line in (Get-Content $propFilePath)){
        $line = $line.trim()
            if (!$line.StartsWith("#")) {
                $jvmArgs += " "
                $jvmArgs += $line
            }
        }
    } 
    return $jvmArgs
}
#function to run a program
function runCommand($arg0, $arg1) {
    $startInfo = New-Object System.Diagnostics.ProcessStartInfo
    $startInfo.FileName = $arg0
    $startInfo.Arguments = $arg1
    #$startInfo.RedirectStandardOutput = $true
    $startInfo.UseShellExecute = $false
    #$startInfo.CreateNoWindow = $false
    #write-output "startInfo: $startInfo"

    $process = New-Object System.Diagnostics.Process
    $process.StartInfo = $startInfo
    $process.Start() | Out-Null
    #$result = $process.StandardOutput.ReadToEnd()
    $process.WaitForExit()
    return 
}

#
# Extracts jar name
#
function getJar($fList, $fTempl) {
	$fList.split(" ") | foreach {
	   $nn = $_
	   $re = $nn -replace "[0-9\.]*\.jar"
	   if ($re -eq $fTempl) {
		  $jarName = "$nn"
          $result = $jarName.trim()
	   }
    }
    return $result
}

